// Theme: shadcn/ui variables mapped to Atomus semantic tokens (shadcn/globals.css).
{
  const g = read('shadcn/globals.css');
  const block = g.match(/^:root, \.dark, \[data-theme\], \[data-brand\] \{([\s\S]*?)\n\}/m);
  const theme = g.match(/^@theme inline \{([\s\S]*?)\n\}/m);
  const variant = g.match(/^@custom-variant dark (.+);$/m);
  if (!block || !theme || !variant) throw new Error('generate: shadcn/globals.css changed shape — update the atomus-theme section of generate.mjs');
  const decls = (s) => Object.fromEntries([...s.matchAll(/--([\w-]+):\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]));
  const vars = decls(block[1]);
  // shadcn adds `--color-<x>: var(--<x>)` to @theme inline for every colour variable itself; keep only the others.
  const themeVars = Object.fromEntries(Object.entries(decls(theme[1])).filter(([k, v]) => v !== `var(--${k.replace(/^color-/, '')})`));
  items.push({
    name: 'atomus-theme',
    type: 'registry:theme',
    title: 'Atomus theme for shadcn/ui',
    description: 'Maps the shadcn/ui variables (background, primary, muted, border, ring, sidebar, chart …) to Atomus semantic tokens, so shadcn/ui components follow the Atomus theme, brand and radius modes.',
    registryDependencies: [url('atomus-tokens')],
    cssVars: { theme: themeVars, light: vars, dark: vars },
    css: {
      // Re-declared on themed elements so a nested data-theme / data-brand switch recomputes them (cssVars only write :root and .dark).
      ':root, .dark, [data-theme], [data-brand]': vars,
      '@layer base': { '*': { '@apply border-border outline-ring/50': {} }, body: { '@apply bg-background text-foreground': {} } },
    },
    docs: docsFor([
      'shadcn/ui variables now point at Atomus tokens. Dark mode: set data-theme="dark" (or the .dark class) on <html>.',
      `For Tailwind's dark: variant to follow data-theme too, use: @custom-variant dark ${variant[1]};`,
      'Brand and shape: data-brand="violet", data-radius="round" | "sharp". Docs: https://docs.atomus.io/code/shadcn/',
    ]),
    categories: ['theme'],
    meta: { source: 'shadcn/globals.css', page: `${SITE}/code/shadcn/` },
  });
}

// Shared helpers + the component CSS that every component uses (font family, .at-icon).
emit('atomus/utils.ts', header('from react/src/utils.ts') + read('react/src/utils.ts'));
items.push({
  name: 'atomus-utils',
  type: 'registry:lib',
  title: 'Atomus utils',
  description: 'Helpers the Atomus components share (cx, useFieldId, useOutsideClick) and their base CSS. Installed automatically with any component.',
  registryDependencies: [url('atomus-tokens')],
  files: [{ path: 'atomus/utils.ts', type: 'registry:lib', target: 'components/atomus/utils.ts' }],
  css: componentCss(['_common'], 'react/src/styles.css'),
  categories: ['lib'],
  meta: { source: 'react/src/utils.ts' },
});

// One registry:ui item per component file.
for (const c of COMPONENTS) {
  let src = read(`react/src/components/${c.file}.tsx`);
  src = src.replace(/from '\.\.\/utils'/g, "from './utils'");
  src = src.replace(/from '\.\/(\w+)'/g, (m, f) => {
    if (f === 'utils') return m;
    if (!fileToItem[f]) throw new Error(`generate: ${c.file}.tsx imports ./${f}, which has no registry item`);
    return `from './${fileToItem[f]}'`;
  });
  const path = `atomus/${c.name}.tsx`;
  emit(path, header(`${c.title} from @stanvision/atomus-react (react/src/components/${c.file}.tsx)`) + src);
  const deps = new Set(['atomus-utils', ...importedItems(src, (p) => (p === './utils' ? null : p.slice(2))), ...(c.cssDeps ?? [])]);
  items.push({
    name: c.name,
    type: 'registry:ui',
    title: c.title,
    description: c.description,
    registryDependencies: [...deps].map(url),
    files: [{ path, type: 'registry:ui', target: `components/atomus/${c.name}.tsx` }],
    css: componentCss(c.css, `react/src/styles.css (${c.title})`),
    docs: docsFor([
      `import { ${c.exports.join(', ')} } from "@/components/atomus/${c.name}";`,
      `Props mirror the Figma component properties. Usage and React API: ${SITE}/${c.page}/`,
      'Prefer the npm package instead? npm i @stanvision/atomus-react and import from "@stanvision/atomus-react".',
    ]),
    categories: ['component'],
    meta: { source: `react/src/components/${c.file}.tsx`, exports: c.exports, page: `${SITE}/${c.page}/` },
  });
}
for (const name of cssSections.keys()) if (!usedSections.has(name)) throw new Error(`generate: react/src/styles.css section "${name}" is not used by any item in scripts/items.mjs`);

