// ---------------------------------------------------------------- write or check

let stale = [];
const keep = new Set([...written.keys()]);
for (const [path, content] of written) {
  // Only registry.json is committed; the source copies and .build/ are written by every build.
  if (check && path !== join(here, 'registry.json')) continue;
  const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
  if (current === content) continue;
  if (check) stale.push(relative(here, path));
  else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
  }
}
// Remove generated files that no longer have a source (component and section copies only, never blocks/).
for (const dir of check ? [] : ['atomus', 'atomus/sections']) {
  if (!existsSync(join(here, dir))) continue;
  for (const f of readdirSync(join(here, dir), { withFileTypes: true })) {
    const p = join(here, dir, f.name);
    if (f.isFile() && !keep.has(p)) {
      if (check) stale.push(`${relative(here, p)} (orphan)`);
      else rmSync(p);
    }
  }
}
if (check && stale.length) {
  console.error(`registry: ${stale.length} generated file(s) are stale — run \`npm run generate\` in registry/:\n  ${stale.join('\n  ')}`);
  process.exit(1);
}
console.log(`registry: ${items.length} items (${COMPONENTS.length} components, ${APP_BLOCKS.length} app blocks, ${SECTIONS.length} website sections)${check ? ' — up to date' : ''}`);
