// Generates the Atomus shadcn registry source from the single sources:
//   react/src/components/*.tsx + react/src/utils.ts   → atomus/*.tsx, atomus/utils.ts      (registry:ui, registry:lib)
//   react/src/styles.css                              → each item's `css` (in @layer components)
//   css/atomus.css                                    → atomus-tokens `css`
//   shadcn/globals.css                                → atomus-theme `cssVars` + `css`
//   sites/docs/src/components/sections/*.tsx + sections.css → atomus/sections/*.tsx (registry:block) + website-parts
//   atomus/blocks/*.tsx + *.css (hand-written)        → app screen blocks
// and writes registry.json (the committed item index) plus .build/registry.json (with each item's CSS, for shadcn build).
// The copies in atomus/*.tsx, atomus/sections/ and .build/ are git-ignored build output.
// Run `node scripts/generate.mjs --check` to fail when the committed registry.json is stale.
//
// Usage: node scripts/generate.mjs [--check]
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync, rmSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { cssToJson } from './css-to-json.mjs';
import { APP_BLOCKS, COMPONENTS, REGISTRY_URL, SITE } from './items.mjs';

const here = new URL('../', import.meta.url).pathname; // registry/
const root = join(here, '..'); // repo root
const out = join(here, 'atomus');
const check = process.argv.includes('--check');
const written = new Map(); // path → content

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
const url = (name) => `${REGISTRY_URL}/${name}.json`;
const read = (p) => readFileSync(join(root, p), 'utf8');
const emit = (path, content) => written.set(join(here, path), content);
const header = (src) => `// Atomus 4.0 — ${src}. MIT licence, https://docs.atomus.io\n// Generated by the Atomus registry (registry/scripts/generate.mjs in github.com/StanVisionAgency/atomus); edit the source there.\n`;

// ---------------------------------------------------------------- exports of @stanvision/atomus-react

/** Maps every export of react/src/index.ts (values and types) to its registry item. */
const exportToItem = {};
const fileToItem = Object.fromEntries(COMPONENTS.map((c) => [c.file, c.name]));
for (const m of read('react/src/index.ts').matchAll(/export \{([^}]+)\} from '\.\/components\/(\w+)'/g)) {
  const item = fileToItem[m[2]];
  if (!item) throw new Error(`generate: react/src/components/${m[2]}.tsx is exported but not listed in scripts/items.mjs`);
  for (const name of m[1].split(',').map((s) => s.trim().replace(/^type\s+/, ''))) exportToItem[name] = item;
}
for (const f of readdirSync(join(root, 'react/src/components')).filter((f) => f.endsWith('.tsx') && !f.includes('.figma.') && !f.includes('.stories.'))) {
  if (!fileToItem[f.replace('.tsx', '')]) throw new Error(`generate: react/src/components/${f} has no registry item — add it to scripts/items.mjs`);
}

/** Rewrites `import { A, type B } from '<barrel>'` into one relative import per registry item. */
function splitBarrelImport(src, barrel, prefix) {
  const re = new RegExp(`import \\{([^}]+)\\} from '${barrel.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&')}';`, 'g');
  return src.replace(re, (_, names) => {
    const byItem = new Map();
    for (const raw of names.split(',').map((s) => s.trim()).filter(Boolean)) {
      const name = raw.replace(/^type\s+/, '');
      const item = exportToItem[name];
      if (!item) throw new Error(`generate: "${name}" is not exported by react/src/index.ts`);
      if (!byItem.has(item)) byItem.set(item, []);
      byItem.get(item).push(raw);
    }
    return [...byItem].map(([item, list]) => `import { ${list.join(', ')} } from '${prefix}${item}';`).join('\n');
  });
}

/** Registry items a TSX file imports through relative paths. */
function importedItems(src, map) {
  const items = new Set();
  for (const m of src.matchAll(/from '(\.{1,2}\/[\w-]+)'/g)) {
    const target = map(m[1]);
    if (target) items.add(target);
  }
  return [...items];
}

// ---------------------------------------------------------------- CSS slices

const styles = read('react/src/styles.css');
const cssSections = new Map();
{
  const headerRe = /^\/\* ([^\n—]+?) — Figma:/gm;
  const marks = [...styles.matchAll(headerRe)];
  cssSections.set('_common', styles.slice(0, marks[0].index));
  marks.forEach((m, i) => cssSections.set(m[1].trim(), styles.slice(m.index, marks[i + 1]?.index ?? styles.length)));
}
const usedSections = new Set(['_common']);
const componentCss = (names, source) => {
  const text = names.map((n) => {
    if (!cssSections.has(n)) throw new Error(`generate: no "/* ${n} — Figma: … */" section in react/src/styles.css`);
    usedSections.add(n);
    return cssSections.get(n);
  }).join('\n');
  return text.trim() ? { '@layer components': cssToJson(text, { source }) } : undefined;
};

